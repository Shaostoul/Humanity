#!/usr/bin/env node
'use strict';
/**
 * ai-catalog.js (`just ai-catalog`, rung 2 of docs/design/embeddable-ai.md, 2026-11-09): write
 * data/ai/catalog.ron, the list of AI files the app may download, from scripts/ai-catalog-recipe.json,
 * and (with --stage) prepare the folder the `assets-ai-1` release will carry.
 *
 * The catalog is COMPILED INTO THE APP (src/ai/catalog.rs, include_str!), so a signed release vouches
 * for every hash in it and a mod cannot point the app at another file (6.2). It is written here,
 * never by hand: for each file the script MEASURES its size and SHA-256 (the engine zip from
 * `just ai-engine package`'s engine.json, each model from its source on this computer), refuses a
 * model whose hash is not its publisher's (`upstream_sha256`), and splits a file of 2 GiB or more into
 * parts (GitHub: "Each file included in a release must be under 2 GiB"), each with its own hash.
 *
 *   node scripts/ai-catalog.js                 write data/ai/catalog.ron
 *   node scripts/ai-catalog.js --stage DIR     also fill DIR with exactly the release's files (each
 *                                              checked after copying) and write DIR/upload-command.txt
 *   node scripts/ai-catalog.js --print         print the catalog instead of writing it
 *
 * Uploading is the top-level session's step, never a dispatched agent's (6.1; docs/ai/release.md):
 * the printed `gh release create ... --latest=false` command is for it.
 * scripts/check-ai-catalog.js (in `just preflight`) checks the result without needing the big files.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const RECIPE = path.join(ROOT, 'scripts', 'ai-catalog-recipe.json');
const CATALOG = path.join(ROOT, 'data', 'ai', 'catalog.ron');
const TWO_GIB = 2 ** 31;
const REPO = 'Shaostoul/Humanity';

function fail(words) {
  console.error(`ai-catalog: ${words}`);
  process.exit(1);
}

/** SHA-256 and size of [start, end) of a file, streamed (a model is gigabytes). */
function hashRange(file, start = 0, end = null) {
  const size = fs.statSync(file).size;
  const stop = end == null ? size : end;
  const h = crypto.createHash('sha256');
  const fd = fs.openSync(file, 'r');
  const buf = Buffer.alloc(8 << 20);
  let at = start;
  try {
    while (at < stop) {
      const n = fs.readSync(fd, buf, 0, Math.min(buf.length, stop - at), at);
      if (n <= 0) throw new Error(`${file} ended at ${at} of ${stop}`);
      h.update(n === buf.length ? buf : buf.subarray(0, n));
      at += n;
    }
  } finally {
    fs.closeSync(fd);
  }
  return { bytes: stop - start, sha256: h.digest('hex') };
}

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

/** The parts of a file of `bytes` (none when it is under 2 GiB): [{ file, start, end }]. */
function partPlan(file, bytes, partBytes) {
  if (bytes < TWO_GIB) return [];
  if (!(partBytes > 0 && partBytes < TWO_GIB)) fail(`part_bytes ${partBytes} must be under 2 GiB`);
  const n = Math.ceil(bytes / partBytes);
  const out = [];
  for (let i = 0; i < n; i++) out.push({ file: `${file}.part${i + 1}of${n}`, start: i * partBytes, end: Math.min(bytes, (i + 1) * partBytes) });
  return out;
}

const q = (s) => JSON.stringify(String(s));

function partsRon(parts, indent) {
  if (!parts.length) return '[]';
  return `[\n${parts.map((p) => `${indent}    (file: ${q(p.file)}, bytes: ${p.bytes}, sha256: ${q(p.sha256)}),`).join('\n')}\n${indent}]`;
}

function catalogRon(cat) {
  const e = cat.engine;
  const lines = [
    '// GENERATED by scripts/ai-catalog.js from scripts/ai-catalog-recipe.json: never edit by hand',
    '// (`just ai-catalog` rewrites it; scripts/check-ai-catalog.js, in `just preflight`, refuses a hand edit',
    '// that no longer matches the recipe). docs/design/embeddable-ai.md, 6.2.',
    '//',
    '// Every AI file HumanityOS may download, with its size and SHA-256. COMPILED INTO THE APP',
    '// (src/ai/catalog.rs), so a signed release vouches for every hash and a mod cannot point the app at',
    '// another file; HUMANITY_AI_CATALOG (a full path) reads a local copy instead, for development only.',
    '// A file of 2 GiB or more is listed as parts, each with its own hash, checked whole after joining.',
    '// A model taken unchanged from its publisher also carries the publisher\'s own hash',
    '// (upstream_sha256), so anyone can compare the project\'s copy with the maker\'s.',
    'AiCatalog(',
    `    release: ${q(cat.release)},`,
    `    base_url: ${q(cat.base_url)},`,
    '    engine: (',
    `        version: ${q(e.version)},`,
    `        platform: ${q(e.platform)},`,
    `        file: ${q(e.file)},`,
    `        bytes: ${e.bytes},`,
    `        sha256: ${q(e.sha256)},`,
    `        parts: ${partsRon(e.parts, '        ')},`,
    `        sources: [${e.sources.map(q).join(', ')}],`,
    `        licence: ${q(e.licence)},`,
    `        licence_text: ${q(e.licence_text)},`,
    `        credits: [${e.credits.map(q).join(', ')}],`,
    '    ),',
    '    models: [',
  ];
  for (const m of cat.models) {
    lines.push(
      '        (',
      `            id: ${q(m.id)},`,
      `            choice: ${q(m.choice)},`,
      `            kind: ${q(m.kind)},`,
      `            model: ${q(m.model)},`,
      `            maker: ${q(m.maker)},`,
      `            licence: ${q(m.licence)},`,
      `            licence_text: ${q(m.licence_text)},`,
      `            finding: ${q(m.finding)},`,
      `            credits: [${m.credits.map(q).join(', ')}],`,
      `            upstream: ${q(m.upstream)},`,
      `            upstream_sha256: ${q(m.upstream_sha256)},`,
      `            file: ${q(m.file)},`,
      `            bytes: ${m.bytes},`,
      `            sha256: ${q(m.sha256)},`,
      `            parts: ${partsRon(m.parts, '            ')},`,
      `            extras: [`,
      ...m.extras.map((x) => `                (file: ${q(x.file)}, install_as: ${q(x.install_as)}, bytes: ${x.bytes}, sha256: ${q(x.sha256)}),`),
      '            ],',
      `            context: ${m.context},`,
      '        ),',
    );
  }
  lines.push('    ],', ')', '');
  return lines.join('\n');
}

/** An extra's bytes: a data file, or text written in the recipe. */
function extraBytes(x) {
  if (x.from) return fs.readFileSync(path.join(ROOT, x.from));
  if (typeof x.text === 'string') return Buffer.from(x.text, 'utf8');
  fail(`the extra ${x.file} has neither "from" nor "text"`);
}

function build(recipe) {
  const pkgPath = path.join(ROOT, recipe.engine.package);
  if (!fs.existsSync(pkgPath)) fail(`${pkgPath} is missing: run \`just ai-engine package\` first`);
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  const zip = path.join(path.dirname(pkgPath), pkg.file);
  const zipNow = hashRange(zip);
  if (zipNow.sha256 !== pkg.sha256 || zipNow.bytes !== pkg.bytes) fail(`${zip} no longer matches ${pkgPath}: package it again`);
  const engine = {
    version: pkg.version,
    platform: recipe.engine.platform,
    file: pkg.file,
    bytes: pkg.bytes,
    sha256: pkg.sha256,
    parts: [],
    sources: [`${pkg.sources.join(', ')} (crate checksum ${pkg.llama_crate_checksum})`],
    licence: recipe.engine.licence,
    licence_text: recipe.engine.licence_text,
    credits: recipe.engine.credits,
    _path: zip,
  };
  if (pkg.bytes >= TWO_GIB) fail('the engine zip is 2 GiB or more');
  const models = [];
  for (const r of recipe.models) {
    if (!fs.existsSync(r.source)) fail(`${r.id}: its source ${r.source} is not on this computer`);
    console.log(`hashing ${r.source} ...`);
    const whole = hashRange(r.source);
    if (r.upstream_sha256 && whole.sha256 !== r.upstream_sha256) fail(`${r.id}: ${r.source} has SHA-256 ${whole.sha256}, its publisher's is ${r.upstream_sha256}: refused`);
    const parts = partPlan(r.file, whole.bytes, recipe.part_bytes).map((p) => ({ ...p, ...hashRange(r.source, p.start, p.end) }));
    const extras = r.extras.map((x) => {
      const data = extraBytes(x);
      return { file: x.file, install_as: x.install_as, bytes: data.length, sha256: sha256(data), _data: data };
    });
    models.push({ ...r, bytes: whole.bytes, sha256: whole.sha256, parts, extras });
  }
  return { release: recipe.release, base_url: recipe.base_url, engine, models };
}

/** Copy `from` to `to`, then check the copy's hash. Always a copy, never a hard link: a link would
 * share its bytes with the original, and `just ai-engine package` rewrites the engine zip in place, which
 * would change the staged file the catalog vouches for under it. */
function place(from, to, expect, start = 0, end = null) {
  if (start === 0 && end == null) {
    fs.copyFileSync(from, to);
  } else {
    const fdIn = fs.openSync(from, 'r');
    const fdOut = fs.openSync(to, 'w');
    const buf = Buffer.alloc(8 << 20);
    let at = start;
    while (at < end) {
      const n = fs.readSync(fdIn, buf, 0, Math.min(buf.length, end - at), at);
      fs.writeSync(fdOut, buf, 0, n);
      at += n;
    }
    fs.closeSync(fdIn);
    fs.closeSync(fdOut);
  }
  const got = hashRange(to);
  if (got.sha256 !== expect.sha256 || got.bytes !== expect.bytes) fail(`${to} does not match after copying`);
}

function stage(cat, dir) {
  fs.mkdirSync(dir, { recursive: true });
  const names = [];
  const put = (name, fn) => {
    const to = path.join(dir, name);
    if (fs.existsSync(to)) fs.rmSync(to);
    fn(to);
    names.push(name);
  };
  put(cat.engine.file, (to) => place(cat.engine._path, to, cat.engine));
  for (const m of cat.models) {
    if (m.parts.length) {
      for (const p of m.parts) put(p.file, (to) => place(m.source, to, p, p.start, p.end));
    } else {
      put(m.file, (to) => place(m.source, to, m));
    }
    for (const x of m.extras) put(x.file, (to) => fs.writeFileSync(to, x._data));
  }
  // Nothing else in the folder: it is exactly what the release carries.
  for (const f of fs.readdirSync(dir)) if (!names.includes(f)) fs.rmSync(path.join(dir, f), { recursive: true });
  const notes = `AI files for HumanityOS (docs/design/embeddable-ai.md). Downloaded only when a person chooses AI in Settings > AI, and checked against the SHA-256 of each file compiled into the app (data/ai/catalog.ron). Contents: the AI engine ${cat.engine.version} (llama.cpp, processor only) and ${cat.models.map((m) => `${m.model} by ${m.maker}`).join(', ')}, each with its licence. Not a game release.`;
  const files = names.sort().map((n) => `"${path.join(dir, n)}"`).join(' ');
  const cmd = `gh release create ${cat.release} --repo ${REPO} --latest=false --title "AI files" --notes "${notes}" ${files}`;
  // Beside the folder, not in it: the folder holds only what the release carries.
  fs.writeFileSync(`${dir}-upload-command.txt`, `${cmd}\n`);
  console.log(`\nStaged ${names.length} files in ${dir}:`);
  for (const n of names.sort()) console.log(`  ${fs.statSync(path.join(dir, n)).size.toString().padStart(13)}  ${hashRange(path.join(dir, n)).sha256}  ${n}`);
  console.log(`\nThe upload (the top-level session runs it, never a dispatched agent), also in ${dir}-upload-command.txt:\n${cmd}`);
}

function main(argv) {
  const recipe = JSON.parse(fs.readFileSync(RECIPE, 'utf8'));
  const cat = build(recipe);
  // --base-url: a developer's catalog pointing at scripts/serve-ai-files.js (loopback only; printed,
  // never written over the built-in one).
  const b = argv.indexOf('--base-url');
  if (b >= 0) {
    const url = argv[b + 1] || '';
    if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+\/$/.test(url)) fail('--base-url must be http://127.0.0.1:<port>/ (a server on this computer)');
    if (!argv.includes('--print')) fail('--base-url is for a developer\'s catalog: use it with --print');
    cat.base_url = url;
  }
  const ron = catalogRon(cat);
  if (argv.includes('--print')) {
    process.stdout.write(ron);
  } else {
    fs.writeFileSync(CATALOG, ron);
    console.log(`wrote ${path.relative(ROOT, CATALOG)}`);
  }
  const s = argv.indexOf('--stage');
  if (s >= 0) {
    if (!argv[s + 1]) fail('--stage needs a folder');
    stage(cat, path.resolve(argv[s + 1]));
  }
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { partPlan, catalogRon, TWO_GIB };
