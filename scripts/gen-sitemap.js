#!/usr/bin/env node
// Write web/sitemap.xml from data/site/public_pages.json (2026-11-02, docs/design/front-door.md 4.5):
// the website's public pages, for search engines. web/robots.txt names it (`Sitemap:`), and
// scripts/sync-web-root.sh puts both at the web root.
//
//   node scripts/gen-sitemap.js           rewrite web/sitemap.xml
//   node scripts/gen-sitemap.js --check   exit 1 when it is not what the data says
//
// No <lastmod>: a date written here would be stale the next day, and an engine reads the pages
// themselves for that. One <url> per row, in the file's order.
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DATA = path.join(ROOT, 'data', 'site', 'public_pages.json');
const OUT = path.join(ROOT, 'web', 'sitemap.xml');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** The sitemap's text for the data. */
function build(data) {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/gen-sitemap.js from data/site/public_pages.json; edit that file, not this one. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ];
  for (const p of data.pages) lines.push('  <url><loc>' + esc(data.origin + p.path) + '</loc></url>');
  lines.push('</urlset>');
  return lines.join('\n') + '\n';
}

if (require.main === module) {
  const want = build(JSON.parse(fs.readFileSync(DATA, 'utf8')));
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== want) {
      console.error('web/sitemap.xml is out of date: run node scripts/gen-sitemap.js');
      process.exit(1);
    }
    console.log('web/sitemap.xml matches data/site/public_pages.json');
  } else {
    fs.writeFileSync(OUT, want);
    console.log('wrote web/sitemap.xml (' + (want.split('<url>').length - 1) + ' pages)');
  }
}

module.exports = { build, DATA, OUT };
