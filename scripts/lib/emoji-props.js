// Unicode's emoji properties as Rust tables, for the desktop's emoji matcher
// (src/gui/widgets/emoji/props.rs, docs/design/emoji.md rung 1). The website's matcher
// (web/shared/emoji.js) asks the JavaScript engine for these properties through \p{...}; the
// desktop asks these tables, made from the same engine's Unicode data, so both apps call the same
// characters emoji.
//
// Why a generated table and not the regex crate's (2026-11-20): regex-syntax 0.8.11, already in
// Cargo.lock, carries Unicode 16.0, and the pack is OpenMoji 17.0.0, which draws Unicode 17.0's new
// emoji (U+1F6D8 landslide, U+1FAEA distorted face, ...): with Unicode 16's tables the desktop would
// show those as text while the website shows pictures. Node 24 carries Unicode 17.0. The comparison
// is in docs/design/emoji.md.
//
// Used by scripts/gen-emoji-props.js (writes the file) and scripts/tests/emoji-props.test.js.

"use strict";

/** The properties the matcher asks about, with the Rust constant each becomes. */
const PROPS = [
  ["Emoji_Presentation", "EMOJI_PRESENTATION"],
  ["Extended_Pictographic", "EXTENDED_PICTOGRAPHIC"],
  ["Emoji_Modifier_Base", "EMOJI_MODIFIER_BASE"],
  ["Emoji_Modifier", "EMOJI_MODIFIER"],
  ["Regional_Indicator", "REGIONAL_INDICATOR"],
];

const RUST_FILE = "src/gui/widgets/emoji/props.rs";

/** Every code point this engine gives `prop`, as inclusive [first, last] ranges. */
function rangesOf(prop) {
  const re = new RegExp(`^\\p{${prop}}$`, "u");
  const out = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue; // surrogates are no characters
    if (!re.test(String.fromCodePoint(cp))) continue;
    const last = out[out.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp;
    else out.push([cp, cp]);
  }
  return out;
}

const hex = (n) => "0x" + n.toString(16).toUpperCase().padStart(4, "0");

/** The Rust file for this engine's Unicode version. */
function rustText() {
  const lines = [
    "// GENERATED by scripts/gen-emoji-props.js from Unicode " + process.versions.unicode + " (the JavaScript",
    "// engine's own Unicode data, the same the website's matcher asks). Do not edit: run",
    "// node scripts/gen-emoji-props.js. Checked by scripts/tests/emoji-props.test.js.",
    "//! Unicode's emoji properties for the desktop's emoji matcher (docs/design/emoji.md, rung 1):",
    "//! inclusive code point ranges, sorted, for a binary search.",
    "",
    `pub(super) const UNICODE_VERSION: &str = "${process.versions.unicode}";`,
  ];
  for (const [prop, name] of PROPS) {
    const ranges = rangesOf(prop);
    lines.push("", `/// \\p{${prop}}: ${ranges.length} ranges.`, `pub(super) const ${name}: &[(u32, u32)] = &[`);
    for (let i = 0; i < ranges.length; i += 6) {
      lines.push("    " + ranges.slice(i, i + 6).map(([a, b]) => `(${hex(a)}, ${hex(b)}),`).join(" "));
    }
    lines.push("];");
  }
  return lines.join("\n") + "\n";
}

/** The tables in a Rust file this module wrote: { version, props: { Emoji_Presentation: [[a, b]] } }. */
function parseRust(text) {
  const version = (text.match(/UNICODE_VERSION: &str = "([^"]+)"/) || [])[1];
  const props = {};
  for (const [prop, name] of PROPS) {
    const m = text.match(new RegExp(`const ${name}: &\\[\\(u32, u32\\)\\] = &\\[([\\s\\S]*?)\\];`));
    props[prop] = m ? [...m[1].matchAll(/\((0x[0-9A-F]+), (0x[0-9A-F]+)\)/g)].map((r) => [parseInt(r[1], 16), parseInt(r[2], 16)]) : null;
  }
  return { version, props };
}

/** -1, 0 or 1 as Unicode version a is older than, the same as or newer than b ("15.1" < "17.0"). */
function compareVersions(a, b) {
  const pa = String(a).split(".").map(Number);
  const pb = String(b).split(".").map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return Math.sign(d);
  }
  return 0;
}

module.exports = { PROPS, RUST_FILE, rangesOf, rustText, parseRust, compareVersions };
