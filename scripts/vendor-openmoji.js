#!/usr/bin/env node
// Copies an OpenMoji release's colour SVGs into assets/emoji/openmoji/, checking each one, and
// rewrites the emoji index (2026-11-20).
//
//   node scripts/vendor-openmoji.js <folder> --version <x.y.z> --sha256 <hash of the zip>
//
// <folder> is where openmoji-svg-color.zip (an OpenMoji release asset, from
// https://github.com/hfg-gmuend/openmoji/releases) was unzipped. The zip is someone else's file:
// unzip it into a new empty folder of its own and run nothing from it. This script only READS the
// folder's .svg files as text.
//
// What it does, and why:
//   - Every picture is checked (scripts/lib/emoji-pack.js `checkSvg`: shapes only, no script, no
//     event attribute, no link or reference out) and every name must be code points. One that fails
//     stops the run with nothing written: a release that suddenly carries a script is a question
//     for a person, not something to copy.
//   - The pictures are copied unchanged, with one exception: a run of characters that is UTF-8 read
//     as Windows-1252 (mojibake) inside the file's text is turned back into the character it was
//     (scripts/check-encoding.js `findMojibake`, the same detector `just lints` runs over the whole
//     tree). OpenMoji 17.0.0 has two such files, 2B1B.svg and E06C.svg, whose path id
//     "groÃŸes schwarzes quadrat" was meant as "großes schwarzes quadrat"; the drawing is untouched.  encoding-exempt: names the mojibake it repairs
//     Each repaired file is named in SOURCE.md, as CC BY-SA 4.0 asks ("indicate if You modified").
//   - Pictures in assets/emoji/openmoji/ that the release no longer has are removed, so the folder
//     is exactly the release.
//   - SOURCE.md records the release, the zip's SHA-256, the count and the repairs; LICENSE.md (the
//     attribution and the licence) is written by hand and left alone.

"use strict";

const fs = require("fs");
const path = require("path");
const pack = require("./lib/emoji-pack");
const { findMojibake } = require("./check-encoding");

function arg(name) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : null;
}

const src = process.argv[2];
const version = arg("--version");
const sha256 = arg("--sha256");
if (!src || src.startsWith("--") || !version || !sha256) {
  console.error("usage: node scripts/vendor-openmoji.js <unzipped folder> --version <x.y.z> --sha256 <zip hash>");
  process.exit(2);
}

const root = path.join(__dirname, "..");
const dst = path.join(root, pack.EMOJI_DIR, "openmoji");

/** One line with its mojibake turned back into the characters it was. */
function repairLine(line) {
  const hits = findMojibake(line);
  if (!hits.length) return line;
  let out = "";
  let at = 0;
  for (const h of hits) {
    out += line.slice(at, h.col - 1) + h.original;
    at = h.col - 1 + h.seq.length;
  }
  return out + line.slice(at);
}

const files = fs.readdirSync(src).filter((f) => f.endsWith(".svg")).sort();
const problems = [];
const repaired = [];
const pictures = new Map();
for (const f of files) {
  const name = f.slice(0, -4);
  if (!pack.NAME_RE.test(name)) problems.push(`${f}: not named by code points`);
  const text = fs.readFileSync(path.join(src, f), "utf8");
  for (const p of pack.checkSvg(text)) problems.push(`${f}: ${p}`);
  const fixed = text.split("\n").map(repairLine).join("\n");
  if (fixed !== text) repaired.push(f);
  pictures.set(f, fixed);
}
const others = fs.readdirSync(src).filter((f) => !f.endsWith(".svg"));
if (others.length) console.log(`(ignored, not .svg: ${others.slice(0, 5).join(", ")}${others.length > 5 ? "..." : ""})`);
if (!files.length) problems.push("no .svg files in " + src);
if (problems.length) {
  console.error(`refused, nothing written (${problems.length} problems):`);
  for (const p of problems.slice(0, 40)) console.error("  " + p);
  process.exit(1);
}

fs.mkdirSync(dst, { recursive: true });
let removed = 0;
for (const f of fs.readdirSync(dst)) {
  if (f.endsWith(".svg") && !pictures.has(f)) {
    fs.unlinkSync(path.join(dst, f));
    removed++;
  }
}
for (const [f, text] of pictures) fs.writeFileSync(path.join(dst, f), text);

const today = new Date().toISOString().slice(0, 10);
const source = [
  "# Where these pictures came from",
  "",
  "GENERATED by `scripts/vendor-openmoji.js`; the attribution and the licence are in",
  "[`LICENSE.md`](LICENSE.md).",
  "",
  `- **Release:** OpenMoji ${version}, the release asset \`openmoji-svg-color.zip\` from`,
  "  <https://github.com/hfg-gmuend/openmoji/releases>.",
  `- **The zip's SHA-256:** \`${sha256}\``,
  `- **Copied:** ${today}, ${pictures.size} pictures (${removed} older ones removed).`,
  "- **Checked:** every picture holds shapes only (no script, no event attribute, no link or",
  "  reference out), by `checkSvg` in `scripts/lib/emoji-pack.js`.",
  "- **Changes:** the drawings are unchanged. " +
    (repaired.length
      ? `In ${repaired.length === 1 ? "one file" : repaired.length + " files"} (${repaired.join(", ")}) a garbled ` +
        "word inside an `id` attribute (UTF-8 text read as Windows-1252) was turned back into the " +
        "characters it was; nothing drawn changed."
      : "No file was changed."),
  "",
];
fs.writeFileSync(path.join(dst, "SOURCE.md"), source.join("\n"));
fs.writeFileSync(path.join(root, pack.INDEX_FILE), pack.indexText(root));
console.log(`copied ${pictures.size} pictures to ${pack.EMOJI_DIR}/openmoji (${removed} removed, ${repaired.length} repaired: ${repaired.join(", ") || "none"}); wrote ${pack.INDEX_FILE}`);
