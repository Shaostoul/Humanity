/// `data/characters/details.ron`, generated by scripts/gen-makehuman-look.js.
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct DetailsDef {
    /// The detail targets' file, relative to the data folder or the repo root.
    pub file: String,
    /// The groups in the character page's order.
    pub groups: Vec<String>,
    pub sliders: Vec<DetailSliderDef>,
}

/// One detail slider: its id (the look's key and the words' `characters.detail_<id>`), its group,
/// the targets its low and high ends drive (a single-target slider has no low end and runs from
/// none to full), the ends' word ids, and the bodies (choice ids) it is for, all when empty.
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct DetailSliderDef {
    pub id: String,
    pub group: String,
    pub low: Vec<String>,
    pub high: Vec<String>,
    pub ends: (String, String),
    #[serde(default)]
    pub bodies: Vec<String>,
}

impl DetailSliderDef {
    /// A slider with one end only, from none (0) to full (1).
    pub fn single(&self) -> bool {
        self.low.is_empty()
    }

    /// Is this slider for the body chosen by `choice`?
    pub fn for_body(&self, choice: &str) -> bool {
        self.bodies.is_empty() || self.bodies.iter().any(|b| b == choice)
    }

    /// A value as this slider takes it: -1 to 1 for a two-ended slider, 0 to 1 for a single one.
    pub fn clamp(&self, v: f32) -> f32 {
        if !v.is_finite() {
            0.0
        } else if self.single() {
            v.clamp(0.0, 1.0)
        } else {
            v.clamp(-1.0, 1.0)
        }
    }
}

/// What a garment is, for the wardrobe and for which defaults it fills.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
pub enum GarmentKind {
    Clothes,
    Shoes,
    Hat,
    Hair,
    Brows,
    Lashes,
}

/// One row of `data/characters/garments.ron`, generated by scripts/gen-makehuman-look.js.
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct GarmentDef {
    pub id: String,
    pub kind: GarmentKind,
    pub file: String,
    /// The texture the game draws (2026-11-10): a DDS of BC7 blocks the converter encoded, the colour
    /// (times its occlusion map) beside the normal map, every level down to 4 texels a half (the
    /// engine's `look_textures`; the source PNGs beside it are what it was made from).
    pub texture: String,
    /// Each half's size at level 0, in texels (1024, or 512 for a source that small: brows, lashes).
    pub texture_px: u32,
    /// Whether the right half is a real normal map (flat otherwise).
    pub normal_map: bool,
    /// The colour half's mean linear luminance (hair tinted by a person's hair colour keeps its
    /// strands' light and dark while its average is the colour chosen).
    pub luma: f32,
    /// The diffuse texture's mean linear colour (a middle body's tint, and the colour a garment is
    /// drawn with until its textures load).
    pub colour: (f32, f32, f32),
    pub roughness: f32,
    /// Cards with alpha (hair, brows, lashes): drawn with the hair material (section 16).
    pub alpha: bool,
    /// Seen from both sides (MakeHuman's `backfaceCull False`): the build adds each triangle's back.
    pub two_sided: bool,
    /// The cover regions under it that are hidden (where its own hidden vertices fall).
    pub covers: Vec<String>,
    #[serde(default)]
    pub tags: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Deserialize)]
struct GarmentsFile {
    garments: Vec<GarmentDef>,
}

/// A garment, read.
#[derive(Debug, Clone)]
pub struct Garment {
    pub def: GarmentDef,
    pub data: GarmentData,
    /// Its cover regions as indices into `BaseShared::region_names`.
    covers: Vec<u8>,
}

/// Everything the look needs that both bodies share, read with the character library.
#[derive(Debug, Clone)]
pub struct LookLibrary {
    pub shared: BaseShared,
    pub details: DetailTargets,
    pub details_def: DetailsDef,
    /// Each slider's low and high targets as indices into `details` (same order as the sliders).
    slider_targets: Vec<(Vec<usize>, Vec<usize>)>,
    pub garments: Vec<Garment>,
}

impl LookLibrary {
    /// Read the shared base mesh, the detail targets and every garment. `read` reads a file by its
    /// data-relative path (the engine's; this crate opens nothing itself but RON).
    pub fn load(data_dir: &Path, shared_file: &str, read: &mut dyn FnMut(&str) -> Result<Vec<u8>, String>) -> Result<Self, String> {
        let text = |rel: &str| -> Result<String, String> {
            let p = data_dir.join("characters").join(rel);
            std::fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display()))
        };
        let shared = BaseShared::parse(&read(shared_file)?)?;
        let details_def: DetailsDef = crate::parse_ron(&text("details.ron")?, "data/characters/details.ron")?;
        let details = DetailTargets::parse(&read(&details_def.file)?)?;
        if details.base_vertices != shared.raw.len() {
            return Err(format!("{}: made for a base mesh of {} vertices, not {}", details_def.file, details.base_vertices, shared.raw.len()));
        }
        let mut seen: Vec<(String, Vec<String>)> = Vec::new();
        let mut slider_targets = Vec::with_capacity(details_def.sliders.len());
        for s in &details_def.sliders {
            if humanity_core::player_look::clean_shape_id(&s.id) != s.id {
                return Err(format!("data/characters/details.ron: slider id {:?} is not one a look can carry", s.id));
            }
            if !details_def.groups.contains(&s.group) {
                return Err(format!("data/characters/details.ron: slider {} has group {}, which is not listed", s.id, s.group));
            }
            if seen.iter().any(|(id, b)| *id == s.id && (b.is_empty() || s.bodies.is_empty() || b.iter().any(|x| s.bodies.contains(x)))) {
                return Err(format!("data/characters/details.ron: slider {} is listed twice for one body", s.id));
            }
            seen.push((s.id.clone(), s.bodies.clone()));
            if s.high.is_empty() {
                return Err(format!("data/characters/details.ron: slider {} drives no target at its high end", s.id));
            }
            let idx = |names: &[String]| -> Result<Vec<usize>, String> {
                names.iter().map(|n| details.index(n).ok_or_else(|| format!("data/characters/details.ron: slider {} names target {n}, which {} does not have", s.id, details_def.file))).collect()
            };
            slider_targets.push((idx(&s.low)?, idx(&s.high)?));
        }
        let gf: GarmentsFile = crate::parse_ron(&text("garments.ron")?, "data/characters/garments.ron")?;
        let mut garments = Vec::with_capacity(gf.garments.len());
        for def in gf.garments {
            if garments.iter().any(|g: &Garment| g.def.id == def.id) {
                return Err(format!("data/characters/garments.ron: garment {} is listed twice", def.id));
            }
            let data = GarmentData::parse(&read(&def.file)?, shared.raw.len()).map_err(|e| format!("garment {}: {e}", def.id))?;
            let covers = def
                .covers
                .iter()
                .map(|c| shared.region(c).ok_or_else(|| format!("garment {}: covers {c}, which is not a cover region", def.id)))
                .collect::<Result<Vec<_>, _>>()?;
            garments.push(Garment { def, data, covers });
        }
        Ok(LookLibrary { shared, details, details_def, slider_targets, garments })
    }

    /// A garment's index by id.
    pub fn garment(&self, id: &str) -> Option<usize> {
        self.garments.iter().position(|g| g.def.id == id)
    }

    /// The detail sliders for a body (choice id), in the page's order.
    pub fn sliders_for<'a>(&'a self, choice: &'a str) -> impl Iterator<Item = &'a DetailSliderDef> + 'a {
        self.details_def.sliders.iter().filter(move |s| s.for_body(choice))
    }
}

/// How far along the skin's normal a garment's cloth may lie, in front of the skin or already behind
/// it, for the skin there to count as under the cloth and be hidden (metres): MakeHuman's clothes sit
/// 2 to 15 mm over the skin, and a pose parts cloth and skin by a centimetre or two where their
/// weights differ.
const COVER_REACH_M: f32 = 0.03;

/// What to build a person from.
#[derive(Debug, Clone)]
pub struct PersonInputs<'a> {
    /// Their shape targets (index, weight): `LoadedBody::shape_for`.
    pub shape: &'a [(usize, f32)],
    /// Their detail slider values by id (a value not here is 0, the body as made).
    pub detail: &'a BTreeMap<String, f32>,
    /// The garments they wear (indices into `LookLibrary::garments`), each drawn in this order.
    pub garments: &'a [usize],
    /// Hide the body under each garment's covered regions (off only for the poke-through check's
    /// red arm).
    pub covers: bool,
    /// Measure the feet's soles from the mesh with the shoes on (off only for the foot probe's red
    /// arm: the soles of the body as made, so a shod foot sinks by its sole).
    pub soles: bool,
}

/// What a drawn primitive of a person's mesh is: one of the body's regions (index into
/// `BodyDef::regions`) or a garment (index into `LookLibrary::garments`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Part {
    Region(usize),
    Garment(usize),
}

/// A person's own mesh, skeleton and feet.
#[derive(Debug, Clone)]
pub struct PersonMesh {
    /// The mesh, without morph targets (its shape is in its vertices).
    pub model: SkinnedModelData,
    /// What each primitive is, in the model's primitive order.
    pub parts: Vec<Part>,
    /// Their skeleton, reshaped from their shaped mesh.
    pub skeleton: Skeleton,
    /// Their legs and soles, measured from this mesh (shoes on).
    pub feet: Option<FootRig>,
    /// How far their shoes' soles stand below the body's floor, metres: the person is drawn this
    /// much higher so the soles, not the feet inside them, stand on the ground.
    pub lift: f32,
    /// Each foot's vertices (primitive, vertex): the foot probe's sole.
    pub foot_vertices: [Vec<(usize, usize)>; 2],
    /// The version it was built for (`look_key`).
    pub key: u64,
}

/// The version of a person's look: a hash of everything their mesh is built from (the body, their
/// shape weights, detail values and garments, and the two check switches), so a changed look always
/// changes it. FNV-1a over the inputs' bits.
pub fn look_key(body: usize, inputs: &PersonInputs<'_>) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    let mut eat = |bytes: &[u8]| {
        for &b in bytes {
            h ^= b as u64;
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    };
    eat(&(body as u64).to_le_bytes());
    for &(t, w) in inputs.shape {
        eat(&(t as u64).to_le_bytes());
        eat(&w.to_bits().to_le_bytes());
    }
    eat(b"|");
    for (k, v) in inputs.detail {
        eat(k.as_bytes());
        eat(&v.to_bits().to_le_bytes());
    }
    eat(b"|");
    for &g in inputs.garments {
        eat(&(g as u64).to_le_bytes());
    }
    eat(&[inputs.covers as u8, inputs.soles as u8]);
    h
}

/// Is a person's mesh to be built again this frame? When there is none, when it was built for
/// another version of their look, and every frame with the reuse switch off (`reuse` false), so a
/// mesh that smells stale is ruled in or out with one click.
pub fn rebuild_due(have: Option<u64>, want: u64, reuse: bool) -> bool {
    !reuse || have != Some(want)
}

/// Build a person's own mesh (the module notes). `body` must carry its base file.
pub fn build_person(body: &LoadedBody, base: &BodyBase, look: &LookLibrary, humanoid: &HumanoidDef, inputs: &PersonInputs<'_>, key: u64) -> PersonMesh {
    let nb = base.positions.len();
    // 1. Each base vertex's detail movement, and its whole shaped place.
    let mut detail = vec![Vec3::ZERO; nb];
    for (s, (low, high)) in look.details_def.sliders.iter().zip(&look.slider_targets) {
        if !s.for_body(&body.choice) {
            continue;
        }
        let v = inputs.detail.get(&s.id).map_or(0.0, |&v| s.clamp(v));
        if v == 0.0 {
            continue;
        }
        let (targets, w) = if v < 0.0 { (low, -v) } else { (high, v) };
        for &t in targets {
            for &(vi, d) in &look.details.targets[t].1 {
                if let Some(slot) = detail.get_mut(vi as usize) {
                    *slot += Vec3::new(d[0] as f32, d[1] as f32, d[2] as f32) * (DETAIL_UNIT_M * w);
                }
            }
        }
    }
    let mut shaped: Vec<Vec3> = base.positions.iter().zip(&detail).map(|(p, d)| Vec3::from(*p) + *d).collect();
    for &(t, w) in inputs.shape {
        if let Some(list) = base.targets.get(t) {
            for &(vi, d) in list {
                if let Some(p) = shaped.get_mut(vi as usize) {
                    *p += Vec3::from(d) * w;
                }
            }
        }
    }

    // 2. The hidden base vertices: each garment's own, inside the regions it covers.
    let mut hidden = vec![false; nb];
    if inputs.covers {
        for &g in inputs.garments {
            let Some(gar) = look.garments.get(g) else { continue };
            for &vi in &gar.data.hidden {
                let r = look.shared.regions.get(vi as usize).copied().unwrap_or(255);
                if gar.covers.contains(&r) {
                    hidden[vi as usize] = true;
                }
            }
        }
    }
    let wears = |k: GarmentKind| inputs.garments.iter().any(|&g| look.garments.get(g).is_some_and(|x| x.def.kind == k));
    let hide_brows = wears(GarmentKind::Brows);
    // The cover regions under any worn garment: there the body is drawn at its shaped base place,
    // without the converter's smoothing of the painted shirt (which made paint read as cloth and
    // stood the skin a few millimetres out, through the real cloth over it: the poke-through test's
    // first run read 69 shirt vertices out at the waist, up to 2.2 cm).
    let mut under = [false; 256];
    for &g in inputs.garments {
        if let Some(gar) = look.garments.get(g) {
            for &r in &gar.covers {
                under[r as usize] = true;
            }
        }
    }
    // Each garment placed on the shaped base mesh (used again for its primitive below).
    let shaped_arr: Vec<[f32; 3]> = shaped.iter().map(|p| p.to_array()).collect();
    let placed: Vec<Vec<[f32; 3]>> = inputs.garments.iter().map(|&g| look.garments.get(g).map_or_else(Vec::new, |gar| gar.data.place(&shaped_arr))).collect();
    // THE SKIN UNDER THE CLOTH: in a region a garment covers, skin with the garment's cloth over it
    // (a ray along the skin's outward normal meeting the cloth within `COVER_REACH_M`, in front or
    // already behind) is hidden too, MakeHuman's own delete_verts kept as well. MakeHuman's list
    // leaves a few vertices under tight cloth and under a top's lower hem, and there the cloth's
    // weights (blended from three body vertices) and the skin's own part by a centimetre or more in
    // a stride, a crouch or a seat: the poke-through test read 6 to 8 vertices through in every pose
    // with MakeHuman's list alone, and 13 to 19 at the sport top's hem in crouch and sit with skin
    // near the cloth hidden but the hem's neighbourhood left. Skin beyond a hem meets no cloth along
    // its normal, so it stays drawn (no hole at a cuff or a collar).
    if inputs.covers {
        // The skin's outward normals at its shaped place (the body's triangles, by base vertex).
        let mut skin_n = vec![Vec3::ZERO; nb];
        let mut g = 0usize;
        for prim in &body.model.primitives {
            for tri in prim.indices.chunks_exact(3) {
                let (Some(a), Some(b), Some(c)) = (base.sole(g + tri[0] as usize), base.sole(g + tri[1] as usize), base.sole(g + tri[2] as usize)) else { continue };
                let f = (shaped[b as usize] - shaped[a as usize]).cross(shaped[c as usize] - shaped[a as usize]);
                for i in [a, b, c] {
                    skin_n[i as usize] += f;
                }
            }
            g += prim.vertices.len();
        }
        for (&gi, pts) in inputs.garments.iter().zip(&placed) {
            let Some(gar) = look.garments.get(gi) else { continue };
            if gar.covers.is_empty() || pts.is_empty() {
                continue;
            }
            // The cloth's triangles (bound vertices) in a grid by their corners.
            let cell = |p: Vec3| ((p.x / COVER_REACH_M).floor() as i32, (p.y / COVER_REACH_M).floor() as i32, (p.z / COVER_REACH_M).floor() as i32);
            let tris: Vec<[Vec3; 3]> = gar.data.indices.chunks_exact(3).map(|t| std::array::from_fn(|i| Vec3::from(pts[gar.data.drawn[t[i] as usize].0 as usize]))).collect();
            let mut grid: std::collections::HashMap<(i32, i32, i32), Vec<u32>> = std::collections::HashMap::new();
            for (ti, t) in tris.iter().enumerate() {
                let mut keys = [cell(t[0]), cell(t[1]), cell(t[2])];
                keys.sort();
                for (k, key) in keys.iter().enumerate() {
                    if k == 0 || *key != keys[k - 1] {
                        grid.entry(*key).or_default().push(ti as u32);
                    }
                }
            }
            for vi in 0..nb.min(look.shared.regions.len()) {
                if hidden[vi] || !gar.covers.contains(&look.shared.regions[vi]) {
                    continue;
                }
                let n = skin_n[vi].normalize_or_zero();
                if n == Vec3::ZERO {
                    continue;
                }
                let p = shaped[vi];
                let (cx, cy, cz) = cell(p);
                'search: for dx in -1..=1 {
                    for dy in -1..=1 {
                        for dz in -1..=1 {
                            let Some(list) = grid.get(&(cx + dx, cy + dy, cz + dz)) else { continue };
                            for &ti in list {
                                let t = &tris[ti as usize];
                                if ray_hit(p, n, t[0], t[1], t[2]).is_some_and(|d| d.abs() <= COVER_REACH_M) {
                                    hidden[vi] = true;
                                    break 'search;
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    // 3. The body's drawn vertices, primitive by primitive.
    let mut model = SkinnedModelData { joints: body.model.joints.clone(), ..Default::default() };
    let mut parts = Vec::new();
    let mut g0 = 0usize; // the glTF vertex index of the primitive's first vertex
    // Normals of the body surface worked out again, welded by base vertex.
    let mut normal_acc = vec![Vec3::ZERO; nb];
    let mut prims: Vec<(usize, Vec<SkinnedVertex>, Vec<u32>)> = Vec::new();
    for (pi, prim) in body.model.primitives.iter().enumerate() {
        let region = body.primitive_regions.get(pi).copied().unwrap_or(0);
        let mut verts = prim.vertices.clone();
        for (i, v) in verts.iter_mut().enumerate() {
            let mut p = Vec3::from(v.position);
            let mut n = Vec3::from(v.normal);
            for &(t, w) in inputs.shape {
                if let Some(m) = prim.morphs.get(t) {
                    p += Vec3::from(m.positions[i]) * w;
                    n += Vec3::from(m.normals[i]) * w;
                }
            }
            if let Some(f) = base.follow.get(g0 + i) {
                for &(vi, w) in f {
                    if w != 0.0 {
                        p += detail[vi as usize] * w;
                    }
                }
            }
            if let Some(vi) = base.sole(g0 + i).filter(|&vi| under[look.shared.regions.get(vi as usize).copied().unwrap_or(255) as usize]) {
                p = shaped[vi as usize];
            }
            v.position = p.to_array();
            v.normal = n.normalize_or_zero().to_array();
        }
        let skip_region = hide_brows && body.def.regions.get(region).is_some_and(|r| r.material == "brows");
        let mut indices = Vec::with_capacity(prim.indices.len());
        for tri in prim.indices.chunks_exact(3) {
            let sole = |k: u32| base.sole(g0 + k as usize);
            let gone = tri.iter().any(|&k| sole(k).is_some_and(|vi| hidden[vi as usize]));
            if gone || skip_region {
                continue;
            }
            indices.extend_from_slice(tri);
            // The welded normal: each face's area-weighted normal onto its corners' base vertices.
            let (a, b, c) = (Vec3::from(verts[tri[0] as usize].position), Vec3::from(verts[tri[1] as usize].position), Vec3::from(verts[tri[2] as usize].position));
            let fnrm = (b - a).cross(c - a);
            for &k in tri {
                if let Some(vi) = sole(k) {
                    normal_acc[vi as usize] += fnrm;
                }
            }
        }
        prims.push((region, verts, indices));
        g0 += prim.vertices.len();
    }
    g0 = 0;
    for (region, mut verts, indices) in prims {
        for (i, v) in verts.iter_mut().enumerate() {
            if let Some(vi) = base.sole(g0 + i) {
                let n = normal_acc[vi as usize];
                if n.length_squared() > 1e-20 {
                    v.normal = n.normalize().to_array();
                }
            }
        }
        g0 += verts.len();
        if indices.is_empty() {
            continue;
        }
        let material = body.def.regions.get(region).map_or_else(String::new, |r| r.material.clone());
        model.primitives.push(SkinnedPrimitiveData { material, vertices: verts, indices, morphs: Vec::new() });
        parts.push(Part::Region(region));
    }

    // 4. The garments, placed on the shaped base mesh (above).
    for (gi, &g) in inputs.garments.iter().enumerate() {
        let Some(gar) = look.garments.get(g) else { continue };
        let placed = &placed[gi];
        // Normals welded by bound vertex.
        let mut acc = vec![Vec3::ZERO; placed.len()];
        for tri in gar.data.indices.chunks_exact(3) {
            let at = |k: u32| Vec3::from(placed[gar.data.drawn[k as usize].0 as usize]);
            let fnrm = (at(tri[1]) - at(tri[0])).cross(at(tri[2]) - at(tri[0]));
            for &k in tri {
                acc[gar.data.drawn[k as usize].0 as usize] += fnrm;
            }
        }
        let vertex = |k: usize, flip: bool| -> SkinnedVertex {
            let (b, uv) = gar.data.drawn[k];
            let (joints, weights) = gar.data.skin[b as usize];
            let n = acc[b as usize].normalize_or_zero();
            SkinnedVertex {
                position: placed[b as usize],
                normal: (if flip { -n } else { n }).to_array(),
                uv,
                joints: joints.map(|j| j as u16),
                weights,
            }
        };
        let n = gar.data.drawn.len();
        let mut verts: Vec<SkinnedVertex> = (0..n).map(|k| vertex(k, false)).collect();
        let mut indices = gar.data.indices.clone();
        if gar.def.two_sided {
            // The back of every card: its own vertices with the normal turned round, wound the other way.
            verts.extend((0..n).map(|k| vertex(k, true)));
            for tri in gar.data.indices.chunks_exact(3) {
                indices.extend_from_slice(&[tri[0] + n as u32, tri[2] + n as u32, tri[1] + n as u32]);
            }
        }
        model.primitives.push(SkinnedPrimitiveData { material: gar.def.id.clone(), vertices: verts, indices, morphs: Vec::new() });
        parts.push(Part::Garment(g));
    }

    // 5. The skeleton from the shaped mesh: each joint the mean of its vertices.
    let joints = body.skeleton.joint_count();
    let moves: Vec<Vec3> = (0..joints)
        .map(|j| match look.shared.joint_verts.get(j) {
            Some(list) if !list.is_empty() => {
                let mut m = Vec3::ZERO;
                for &vi in list {
                    m += shaped[vi as usize] - Vec3::from(base.positions[vi as usize]);
                }
                m / list.len() as f32
            }
            _ => Vec3::ZERO,
        })
        .collect();
    let skeleton = body.skeleton.reshaped(&moves);

    // 6. The feet, measured from this mesh with its shoes on.
    let foot_vertices = match FootRig::new(&skeleton, humanoid) {
        Some(rig) => feet_of(&model, &rig),
        None => Default::default(),
    };
    let (feet, lift) = match FootRig::new(&skeleton, humanoid) {
        None => (None, 0.0),
        Some(rig) => {
            let at_rest = foot_vertices.clone().map(|v| v.iter().map(|&(p, k)| Vec3::from(model.primitives[p].vertices[k].position)).collect::<Vec<Vec3>>());
            // The soles first: the toe cap and heel counter are measured from them.
            let (rig, lift) = if inputs.soles { rig.with_soles(&skeleton, &at_rest) } else { (rig, 0.0) };
            (Some(rig.with_extents(&skeleton, &at_rest)), lift)
        }
    };
    PersonMesh { model, parts, skeleton, feet, lift, foot_vertices, key }
}

/// Where the line through `o` along `d` meets triangle (a, b, c): the signed distance along `d` (a
/// unit vector), or None (Moller and Trumbore's test, both directions).
fn ray_hit(o: Vec3, d: Vec3, a: Vec3, b: Vec3, c: Vec3) -> Option<f32> {
    let e1 = b - a;
    let e2 = c - a;
    let h = d.cross(e2);
    let det = e1.dot(h);
    if det.abs() < 1e-14 {
        return None;
    }
    let s = o - a;
    let u = s.dot(h) / det;
    if !(0.0..=1.0).contains(&u) {
        return None;
    }
    let q = s.cross(e1);
    let v = d.dot(q) / det;
    if v < 0.0 || u + v > 1.0 {
        return None;
    }
    Some(e2.dot(q) / det)
}

/// Each foot's vertices (primitive, vertex), left then right: those whose largest weight is on that
/// leg's foot or toes joint, the body's and a shoe's alike.
pub fn feet_of(model: &SkinnedModelData, rig: &FootRig) -> [Vec<(usize, usize)>; 2] {
    let mut out: [Vec<(usize, usize)>; 2] = Default::default();
    for (pi, p) in model.primitives.iter().enumerate() {
        for (vi, v) in p.vertices.iter().enumerate() {
            let k = (0..4).max_by_key(|&k| v.weights[k]).unwrap_or(0);
            if v.weights[k] == 0 {
                continue;
            }
            let j = v.joints[k] as usize;
            for (side, leg) in rig.legs.iter().enumerate() {
                if j == leg.foot || j == leg.toes {
                    out[side].push((pi, vi));
                }
            }
        }
    }
    out
}

