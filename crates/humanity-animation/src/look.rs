//! THE LOOK: each person's own shaped and dressed mesh (character animation, "the look",
//! 2026-11-09; docs/design/character-animation.md section 16).
//!
//! With fifteen shape targets a body could carry its shape on the GPU (`pose::MORPH_SLOTS`, a few
//! targets added to each vertex every frame). With MakeHuman's face and body detail targets, hundreds
//! of them, and garments that must fit whatever shape results, that stops scaling, so each near
//! person is BUILT ONCE when their look changes, on the CPU, into their own vertex data:
//!
//! 1. every base-mesh vertex (the body and MakeHuman's helpers) moved by the person's shape targets
//!    and detail targets (`BodyBase`, `DetailTargets`);
//! 2. the body's drawn vertices moved with them (each follows its base vertices) and their normals
//!    worked out again from the shaped surface; the triangles under a worn garment's covered regions
//!    dropped, so skin never pokes through (`covers`);
//! 3. each garment, hair, brows or lashes placed on the SHAPED base mesh by its MakeHuman binding,
//!    so every shape and detail target fits it, and skinned with the bound body vertices' weights;
//! 4. the skeleton made again from the shaped mesh (a joint is the mean of its vertices), and the
//!    feet's sole heights, reach, toe cap and heel counter measured from the person's OWN mesh with
//!    their shoes on (rung 2a's lesson: whatever is measured from the body must reach each person's
//!    copy; a shoe's sole raises the person by its thickness, `PersonMesh::lift`).
//!
//! The result is tagged with a version made from everything it was built from (`look_key`), so the
//! engine builds again exactly when the look changes, and, with the reuse switch off
//! (`humanity_core::reuse`), every frame (`rebuild_due`): CLAUDE.md's no-caches rule.
//!
//! Middle and far bodies keep the shared body with its macro shape on the GPU (measured: section
//! 8.3 and 8.4 of the plan).

